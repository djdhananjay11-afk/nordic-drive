export function formatNok(value: number) {
  return new Intl.NumberFormat("nb-NO", {
    style: "currency",
    currency: "NOK",
    maximumFractionDigits: 0,
  }).format(value);
}

export function getCarBySlug(brandSlug: string, modelSlug: string) {
  return nordicCars.find((car) => car.brandSlug === brandSlug && car.modelSlug === modelSlug);
}

export function getEfficiencyScore(car: NordicCar) {
  return Math.round((car.winterRangeKm / car.batteryKwh) * 10) / 10;
}

export function getCarKey(car: Pick<NordicCar, "brandSlug" | "modelSlug">) {
  return `${car.brandSlug}-${car.modelSlug}`;
}

export function getFallbackCarImageUrl(car: Pick<NordicCar, "brandSlug" | "modelSlug">) {
  return `/vehicle-images/${getCarKey(car)}.svg`;
}

export function getCarImageAsset(car: Pick<NordicCar, "brandSlug" | "modelSlug" | "imageUrl">) {
  if (car.imageUrl) {
    return {
      media: undefined,
      url: car.imageUrl,
    };
  }

  const media = getOfficialCarMedia(getCarKey(car));

  return {
    media,
    url: media?.url ?? getFallbackCarImageUrl(car),
  };
}

export function getCarImageUrl(car: Pick<NordicCar, "brandSlug" | "modelSlug" | "imageUrl">) {
  return getCarImageAsset(car).url;
}

export function getCarImageCredit(car: Pick<NordicCar, "brandSlug" | "modelSlug">) {
  return getOfficialCarMedia(getCarKey(car));
}
