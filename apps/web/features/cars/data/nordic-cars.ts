export type NordicCar = {
  brand: string;
  model: string;
  brandSlug: string;
  modelSlug: string;
  tagline: string;
  segment: "SUV" | "Sedan" | "Crossover" | "Wagon";
  priceNok: number;
  monthlyNok: number;
  rangeWltpKm: number;
  winterRangeKm: number;
  chargingMinutes: number;
  fastChargingKw: number;
  batteryKwh: number;
  accelerationSeconds: number;
  drivetrain: "RWD" | "AWD";
  heatPump: boolean;
  towingKg: number;
  seats: number;
  highlights: string[];
  colorClass: string;
  imageUrl?: string;
  imageAlt?: string;
};

export type NordicLaunch = {
  brand: string;
  model: string;
  expected: string;
  estimateNok: number;
  confidence: "Confirmed" | "Likely" | "Rumored";
  note: string;
};

type CarInput = Omit<NordicCar, "imageAlt"> & {
  imageAlt?: string;
};

function car(input: CarInput): NordicCar {
  return {
    ...input,
    imageAlt: input.imageAlt ?? `${input.brand} ${input.model} electric car`,
  };
}

